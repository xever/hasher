import Foundation

// ============================================================================
// 单个文件的哈希计算结果
// ----------------------------------------------------------------------------
// 引擎计算完成后，把每个文件的“信息 + 各算法哈希值”打包成这个结构，
// 界面层再根据用户勾选的选项决定显示哪些内容、如何排版。
// ============================================================================

/// 单个文件的哈希计算结果
struct FileHashResult {
    /// 文件的完整路径
    let path: String
    /// 文件大小（字节）
    let sizeBytes: Int64
    /// 文件版本（仅 .app 等 bundle 才有意义，普通文件为 "—"）
    let version: String
    /// 修改时间（格式 yyyy-MM-dd HH:mm:ss）
    let modifiedTime: String
    /// 各算法的哈希值（键为算法，值为小写十六进制字符串）
    let hashes: [HashAlgorithm: String]
}
